#!/usr/bin/env bash
# ============================================================
# switches.sh — 주행 스위치 **한 벌**. 모든 입구가 이것을 읽는다.
#
#     run_record.sh    백엔드가 띄우는 것 (edge/recorder.py:104)
#     run_headless.sh  렌더 없는 짝
#     run_traj.sh      궤적 재생 (run_headless 를 부른다)
#
# 왜 이 파일이 생겼나 (2026-09-22)
# --------------------------------
# 이 값들이 **어디에도 안 적혀 있었다.** 매 판 손으로 export 해 왔고, 백엔드
# 경로는 아예 못 받았다. 그래서 두 가지가 계속 났다.
#
#   ① 「지난 판이 무슨 설정이었나」를 로그 본문에서 되짚어야 했다
#   ② 백엔드 주행과 손 주행이 **다른 설정**으로 돌았다
#
# ★ 전부 `${VAR:-기본}` 이다 — 셸이나 호출자가 준 값이 이긴다. 한 변수만
#   바꿔 비교할 수 있다.
#
# ☹ 셸에 옛 export 가 남아 있으면 그것이 이긴다. 깨끗이 돌리려면
#       for v in $(compgen -v | grep ^PIBT_); do unset "$v"; done
# ============================================================

# --- 공차 ---------------------------------------------------
#   ★ 0.05 를 쓰면 안 된다. isaac_drive.py:1633 이 못 박아 뒀다 —
#     `pos=0.05` 는 **pitch 1.2 에서 정해진 값**인데 1.0 에서는 기하 여유가
#     `1.0 - 0.400 - 0.5587 = 41.3 mm` 뿐이라 **허용오차가 예산보다 크다.**
#     도착 판정이 `hypot(dx,dy) <= pos` 라 로봇은 늘 원의 가장자리에 서고
#     (실측 중앙 -45.7 mm), 옆에서 누가 돌면 닿는다 — **5판 중 2판이 실제로
#     차체 접촉으로 중단됐다.**
#   ☹ 0.02 는 반대로 회전 교착이 난다. 제어 정착 바닥이 20.0 mm 라 기하
#     요구(20.65 mm)와 창이 0.65 mm 뿐이다. 0.03 이 실측으로 도는 값이다.
export PIBT_TOL_POS="${PIBT_TOL_POS:-0.03}"
export PIBT_TOL_CROSS="${PIBT_TOL_CROSS:-0.03}"

# --- 회전 대기 관문 -----------------------------------------
#   남의 **몸**이 내 스윙 칸에 있으면 회전을 시작하지 않는다. 계획(SWING_HARD)도
#   ADG(ADG_BODY)도 이 배치를 못 막는다 — 둘 다 **액션**을 보는데 상대는
#   **액션 없이 서 있다.**
#
#   한도를 90 으로 둔다 (코드 기본 10 · 예전 실험값 30).
#       사고 ①은 34.8초 기다려야 했는데 30초로 잘려 4.8초 모자랐다
#       실측 30 -> 90  :  차체 접촉 1 -> 0 · worst_gap ~0.8 -> 42.19 mm
#                         turn_gaveup_body 39/39 -> 9
#   ☹ 대가가 크다 — 액션 속도 2.96 -> 1.59 /s (-46 %) · 회전 관문 대기가
#     로봇 시간의 15.4 %. 문서의 어림(-0.4 %)은 크게 틀렸다.
#   한도에 닿으면 isaac_drive.py:3216 이 반드시 출발시키므로 **영구 교착은
#   구조상 안 난다.** 올려서 사는 것은 교착이 아니라 기다림이다.
export PIBT_TURN_BODY_GATE="${PIBT_TURN_BODY_GATE:-1}"
export PIBT_TURN_BODY_MAX="${PIBT_TURN_BODY_MAX:-90}"
export PIBT_TURN_YIELD="${PIBT_TURN_YIELD:-1}"

# --- 회전 각가속 제한 ---------------------------------------
#   회전 가지에는 가속도 제한이 **없었다.** 직진은 한 스텝에 a_exec 만큼만
#   바뀌는데 회전은 `clamp(3*err, +-w_max)` 를 그대로 돌려준다. 90도면
#   3*1.571 = 4.71 이라 **첫 스텝에 곧바로 w_max(2.07)** 다. 60 Hz 에서 바퀴
#   접선속도 0.83 m/s 짜리 계단이고, 속도 제어 조인트에 계단을 주면 마찰
#   한도를 잠깐 넘어 미끄러진다. 162건 중 1건이 363.4 mm 밀렸고 시작 48.4 ->
#   끝 363.4 이므로 **회전 그 자체가 315 mm 를 만들었다.**
#
#   20 이면 한 스텝 변화가 2.07 -> 0.33 rad/s 로 6배 작아지고 90도 소요는
#   0.76 -> 0.81 s 라 거의 안 변한다. TURN_TICKS=5 는 FMS 와 공유하므로 그
#   틱 모델이 깨지면 안 된다 — 그래서 20 이다.
#   ☹ 구현은 2026-09-17 인데 기본이 0(꺼짐)이라 **아직 판으로 확인 못 했다.**
export PIBT_W_ACCEL="${PIBT_W_ACCEL:-20}"

# --- 회전 완료 관문 · 복구 기동 -----------------------------
#   회전은 isaac_drive.py:2145 에서 일찍 반환한다 — `return (0.0, w)` 라
#   **v 가 항상 0 이다.** 즉 회전은 병진을 못 한다. 그런데 완료 판정에는
#   위치가 들어 있어(-240), 회전이 끝난 뒤 위치가 관문을 넘으면 그 액션 안에
#   고칠 수단이 없어 **영영 안 끝난다.**
#
#   코드 기본 0.100 을 그대로 쓴다. 실측 분포가 근거다 (회전 55건)
#       중앙 33.02 · p95 45.62 · 최대 51.23 mm  ->  **관문 100 초과 0건**
#       관문을 0.05 로 조이면 51.23 mm 한 건에 판이 죽는다 (2026-09-22 실제)
#   조여도 측정에는 기여하지 않는다 — 밀림은 `[회전분포]` 히스토그램이 관문과
#   무관하게 따로 잰다.
export PIBT_TOL_TURN_POS="${PIBT_TOL_TURN_POS:-0.100}"

#   ☹ 복구 기동은 **회전에 안 듣는다.** 그 코드는 위 early return 아래
#     직선 추종 가지에 있다. 직선의 횡오차 고정점에만 듣는다 —
#     `d(cross)/dt = -w * along` 이라 병진만으로는 횡오차가 안 줄어서
#     조향을 직접 줘야 풀리는 그 경우다.
export PIBT_RECOVER="${PIBT_RECOVER:-1}"

#   ★★ 도착 판정에 「서 있는가」 — 기본 **0 = 꺼짐** (2026-09-22, 미검증).
#
#   지금 오차는 물리 한계가 아니라 **판정이 만든다.** 도착이 원에 **들어오는
#   순간**이라 로봇은 목표가 아니라 원의 가장자리에 선다 (실측 중앙 -45.7 mm
#   / 허용 50). 그래서 회전 위치오차 중앙이 32.32 mm 인데, 그중 ~30 mm 가
#   tol.pos 그 자체다. 평상 분포는 중앙 5.32 mm 다.
#
#   0.02 를 주면 감속 램프가 목표까지 끝난다. 오차가 공차가 아니라 램프
#   해상도(~3 mm)에 묶인다.
#
#   ☹ 완주 판(2026-09-22)의 `worst_gap` 이 **3.39 mm** 였다. 접촉은 0 이지만
#     설계 예산 41.3 mm 의 8 % 다. 이 대책은 그 여유를 되찾으려는 것이다.
#   ☹ 대가 — 마지막 몇 cm 를 저속으로 가서 액션마다 조금 느려진다.
#     이어달리기(exit_v > 0)에는 안 걸린다 (걸면 교착).
#   ★ 2026-09-22 실측으로 **기본을 켠다** (0 -> 0.02).
#
#       worst_gap    3.39 mm  ->  19.04 mm      5.6배 · 예산 41.3 의 46 %
#       sim_time    3,768.7 s ->  3,823.2 s     +1.4 % (54.5초)
#       stall_steps   72,954  ->  69,700        -4.5 % (**줄었다**)
#       contact_events     0  ->       0
#       turn_body_gaveup  64  ->      64        관문은 한 글자도 안 바뀌었다
#
#     기다림을 더 살 줄 알았는데 정체가 오히려 줄었다 — 제대로 서고
#     출발하니 뒤가 덜 막힌다. 여유 5.6배를 시간 1.4 % 로 샀다.
export PIBT_TOL_STOP_V="${PIBT_TOL_STOP_V:-0.02}"

# --- 작업부하 (계획 판에만 걸린다) ------------------------
#   ★★ 2026-09-22 — **우리 기본값이 FMS 판과 다른 문제를 풀고 있었다.**
#
#   r13 궤적에서 직접 셌다 (추측 아님)
#
#       태스크 258건 = 43트립 x 6토트 · 단독 트립 0건 · 전부 out
#       서비스 연속 구간 121틱(33.61 s)이 57/59건 = 96.6 %
#
#   그런데 우리 기본은 CAPACITY=1 · SVC_PER_TOTE=0 이라 서비스가 4틱(1.11 s)
#   이다. **30배 짧다.** 그 기본으로 만든 판은 FMS 판과 비교할 수 없다.
#   lifelong.py:131 이 「그쪽과 맞댈 판에서는 같은 값을 줘야 한다」고 이미
#   적어 뒀는데 기본값이 따라가지 않았다.
#
#   ☹ 남는 9틱 — 우리 모델은 service_steps(4) + 6 x svc_per_tote(18) = 112틱
#     인데 관측은 121틱이다. `4 + 6*per = 121` 을 만족하는 정수 per 가 없다.
#     틱 해상도 차이인지 라벨 경계인지 **안 밝혔다.** FMS 에 물을 것.
#
#   ☹ 이 값을 켜면 서비스가 길어져 **처리량이 크게 떨어진다.** 맞는 값이지만,
#     우리 옛 판들(기본 1/0)과는 직접 비교하면 안 된다.
#
#   궤적 재생 판에는 영향이 없다 — 계획을 안 하므로 배차가 안 돈다.
export PIBT_CAPACITY="${PIBT_CAPACITY:-6}"
export PIBT_SVC_PER_TOTE="${PIBT_SVC_PER_TOTE:-18}"

# --- ADG --------------------------------------------------
#   ☹ **이 둘은 확정이 아니다.** docs/LOCAL_작업순서.md 가 대가를 적어 뒀다 —
#     `-6.2 % · 포기 5.8배 · 정체 8배 · 최소간격 42 -> 0.64 mm`. 그리고
#     2026-09-21 제안서는 **둘 다 끄고 안전을 기하 하나에 두자**고 한다.
#     다만 그 제안은 아직 한 판도 안 돌렸고, 이 둘을 켠 최근 판이
#     worst_gap 42.19 mm 로 예산을 회복했다. 그래서 일단 켠 채로 둔다.
#     끄고 비교하려면 `PIBT_ADG_BODY=0 PIBT_ADG_RANK=0`.
export PIBT_ADG_BODY="${PIBT_ADG_BODY:-1}"
export PIBT_ADG_RANK="${PIBT_ADG_RANK:-1}"

# --- 무엇으로 도는지 한 눈에 -------------------------------
#   ★ 이 배너가 이 파일의 절반이다. 지난 판들이 무슨 설정이었는지 로그
#     본문에서 뒤늦게 알아내야 했다. 이제 **첫 줄로 확정된다.**
_sw_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
echo "──────────── 주행 스위치 ────────────"
echo "  코드        $(git -C "$_sw_dir" rev-parse --short HEAD 2>/dev/null || echo '?')  $(git -C "$_sw_dir" symbolic-ref --short HEAD 2>/dev/null || echo '?')"
echo "  공차        pos $PIBT_TOL_POS · cross $PIBT_TOL_CROSS"
echo "  회전 관문   대기 ${PIBT_TURN_BODY_MAX}s (켬 $PIBT_TURN_BODY_GATE · 양보 $PIBT_TURN_YIELD) · 완료 ${PIBT_TOL_TURN_POS} m"
echo "  회전 가속   ${PIBT_W_ACCEL} rad/s^2$([ "$PIBT_W_ACCEL" = "0" ] && echo '   ☹ 꺼짐 — 계단 그대로')"
echo "  복구 기동   $PIBT_RECOVER   (회전에는 안 듣는다)"
echo "  정지 판정   ${PIBT_TOL_STOP_V} m/s$([ "$PIBT_TOL_STOP_V" = "0" ] && echo "   (꺼짐 — 원 가장자리에 선다)")"
echo "  ADG         몸 $PIBT_ADG_BODY · 순위 $PIBT_ADG_RANK"
echo "  작업부하    토트 ${PIBT_CAPACITY}개 · 토트당 ${PIBT_SVC_PER_TOTE}틱   (궤적 재생 판에는 무관)"
echo "  격자        pitch ${PIBT_PITCH:-?} · 앞 칸 규칙 ${PIBT_FRONT_RULE:-?} · FMS 격자 ${PIBT_FMS_GRID:-0}"
echo "  회전 마스크 ${PIBT_TURN_SWEEP:-1}$([ -n "${PIBT_TRAJ:-}" ] && echo '   (궤적 재생 — 계획을 안 하므로 무의미)')"
echo "─────────────────────────────────────"
unset _sw_dir
