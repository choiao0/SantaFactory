package com.ssafy.santafactory.entity.estimate;

/** 권장 대수를 내지 못한 사유. */
public enum ReasonCode {

    /** 모든 대수가 예산을 넘는다. */
    BUDGET_EXCEEDED,

    /** 예산 안에 드는 대수는 있으나, 목표 처리량에 닿는 대수가 없다. */
    THROUGHPUT_SHORT,

    /** 목표 처리량은 채우지만 그 대수의 가동률이 목표에 못 미친다. */
    UTILIZATION_SHORT,

    /** 시뮬이 전 대수 실패해 판정할 결과가 하나도 없다. */
    ALL_FAILED,

    /**
     * 전 대수가 처리율 100 % — 처리율이 대수를 구분하지 못해 판정할 수 없다.
     *
     * <p>대개 시뮬이 고정 시간 모드가 아니라 유한 주문 모드로 돌았다는 신호다(주문을 다 처리하고
     * 종료하면 완료율이 항상 100 %). 이 상태로 판정하면 가동률이 가장 높은 최소 대수, 즉 "1대 권장"
     * 이라는 틀린 답이 나오므로 권장을 내지 않는다. 부하가 실제로 아주 낮은 창고여도 같은 값이 나오니
     * 시뮬 실행 조건을 먼저 확인해야 한다.
     */
    LOAD_TOO_LOW
}
