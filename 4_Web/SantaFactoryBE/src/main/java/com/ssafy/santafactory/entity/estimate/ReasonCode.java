package com.ssafy.santafactory.entity.estimate;

/** 권장 대수를 내지 못한 사유. */
public enum ReasonCode {

    /** 모든 대수가 예산을 넘는다. */
    BUDGET_EXCEEDED,

    /** 예산 안에 드는 대수는 있으나, 목표 처리량에 닿는 대수가 없다. */
    THROUGHPUT_SHORT,

    /** 목표 처리량은 채우지만 그 대수의 가동률이 목표에 못 미친다. */
    UTILIZATION_SHORT,

    /**
     * 처리율·가동률·예산은 맞지만 주문 리드타임 p90 이 상한을 넘는다 (S15P21A106-97).
     *
     * <p>"주문은 다 나가지만 한 건이 오래 걸리는" 구성을 걸러낸다. 대수가 늘면 대기가 줄어
     * 만족하기 쉬워지므로 처리율과 같은 방향(대수 하한)으로 작용한다 — 이 사유가 나오면
     * 대수를 더 쓰거나 상한({@code estimate.lead-time-p90-limit})을 완화해야 한다.
     */
    LEAD_TIME_LONG,

    /** 시뮬이 전 대수 실패해 판정할 결과가 하나도 없다. */
    ALL_FAILED,

    /**
     * <b>더 이상 만들어지지 않는다</b> — 옛 견적 행을 읽기 위해 남겨 둔 값이다 (S15P21A106-97).
     *
     * <p>전 대수가 처리율 100 % 일 때 판정을 거부하던 사유다. 시뮬이 고정 시간 모드가 아니라 유한 주문
     * 모드로 돌면 완료율이 항상 100 % 가 되는데, 그 오작동을 걸러내려고 뒀었다. 지금은 요청이 horizon
     * 을 명시하고 출고 주문 목록을 직접 싣기 때문에(S15P21A106-214) 그 상태가 될 수 없고, 남겨 두면
     * 대수 범위를 좁게 고른 정상적인 견적이 — 그 구간은 전부 처리율이 같으니 — 답을 못 받는다.
     * 대신 가동률 조건이 "조건을 만족하는 최소 대수"를 고른다.
     */
    LOAD_TOO_LOW
}
