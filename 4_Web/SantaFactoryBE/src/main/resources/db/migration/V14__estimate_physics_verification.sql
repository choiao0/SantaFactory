-- DES 피크 구간 → 물리 검증(Isaac) 연결, 대수별 검증 (S15P21A106-244).

-- run 하나의 DES 피크 구간(gzip+base64 궤적). RunReplay(V9)와 같은 자리(scenario_id 1:1)를 쓰지만
-- 저장 목적이 달라 별도 테이블이다 — 여긴 물리 검증에만 쓰고 화면 재생에는 쓰지 않는다.
-- 구간을 못 만든 run 도 사유를 보여야 해서 gz_b64 없이 meta_json 만 있는 행이 있을 수 있다.
CREATE TABLE simscenario_verify_slices (
    scenario_id BIGINT PRIMARY KEY REFERENCES simscenarios (scenario_id) ON DELETE CASCADE,
    meta_json   TEXT NOT NULL,
    gz_b64      TEXT
);

-- 견적×대수 하나의 물리 검증 회차. 같은 (estimate_id, n_robots) 를 다시 검증하면 attempt 를 올려
-- 새 행을 쌓는다 — estimates.verify_* (V8, 견적당 한 벌)와 달리 여러 대수를 동시에 검증해야 해서다.
CREATE TABLE estimate_verifications (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estimate_id      BIGINT NOT NULL REFERENCES estimates (estimate_id) ON DELETE CASCADE,
    n_robots         INTEGER NOT NULL,
    attempt          INTEGER NOT NULL,
    run_id           VARCHAR(64) NOT NULL UNIQUE,
    status           VARCHAR(16) NOT NULL,
    error            VARCHAR(500),
    reason           VARCHAR(64),
    video_key        TEXT,
    physics_json     TEXT,
    verify_json      TEXT,
    slice_meta_json  TEXT,
    requested_at     TIMESTAMP NOT NULL,
    finished_at      TIMESTAMP
);

-- 대수별 최신 시도 조회(상세·SSE)와 "이 견적에 진행 중인 회차가 있나" 가드가 여기로 찾는다.
CREATE INDEX idx_estimate_verifications_estimate_n ON estimate_verifications (estimate_id, n_robots);
