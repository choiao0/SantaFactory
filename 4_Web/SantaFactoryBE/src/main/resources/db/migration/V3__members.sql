-- 회원과 창고 소유권 (S15P21A106-186)
--
-- 관리자를 별도 테이블로 나누지 않고 role 컬럼으로 구분한다. 관리자도 이메일·비밀번호로
-- 로그인하므로 테이블을 나누면 인증 경로가 두 벌이 된다. 역할이 둘뿐이고 겸직이 없어
-- 조인 테이블(member_roles)도 필요 없다.
--
-- company·phone 은 B2B 리드 정보라 가입자에게 필수다. 관리자 행도 같은 제약을 받으므로
-- 계정 초기화 코드가 자기 값을 채운다.
CREATE TABLE members (
    member_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL UNIQUE,
    password   VARCHAR(60)  NOT NULL,   -- BCrypt 해시 고정 길이
    name       VARCHAR(50)  NOT NULL,
    company    VARCHAR(100) NOT NULL,
    phone      VARCHAR(20)  NOT NULL,   -- 하이픈 제거 후 숫자만 저장
    role       VARCHAR(20)  NOT NULL,   -- USER | ADMIN
    created_at TIMESTAMP    NOT NULL
);

-- 창고 소유자.
--
-- nullable 인 이유: 이 마이그레이션이 도는 시점에 이미 시드 창고가 있는데 붙일 회원이 없다.
-- 시드(R__seed_demo.sql)는 반복 마이그레이션이라 모든 버전 마이그레이션 뒤에 돌아서 앞당길
-- 수 없다. NOT NULL 을 걸려면 데모 회원을 이 파일에 INSERT 해야 하고, 그러면 시연 계정이
-- 되돌릴 수 없게 버전 마이그레이션에 박힌다.
--
-- 대신 애플리케이션이 강제한다 — 창고 생성 API 가 항상 세션 회원을 붙이고, 주인 없는 창고
-- (= 시드에서 온 것)는 계정 초기화가 데모 회원에게 귀속시킨다.
ALTER TABLE warehouses
    ADD COLUMN member_id BIGINT;

ALTER TABLE warehouses
    ADD CONSTRAINT fk_warehouses_member FOREIGN KEY (member_id) REFERENCES members (member_id);

-- "내 창고" 조회가 member_id 로 필터한다. Postgres 는 FK 컬럼에 인덱스를 자동 생성하지 않는다.
CREATE INDEX idx_warehouses_member ON warehouses (member_id);
