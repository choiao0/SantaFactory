CREATE TABLE warehouses (
    warehouse_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(100) NOT NULL DEFAULT '품고',
    area                 DOUBLE PRECISION NOT NULL,
    width                DOUBLE PRECISION NOT NULL,
    length               DOUBLE PRECISION NOT NULL,
    worker_count         INTEGER NOT NULL,
    inbound_start        TIMESTAMP NOT NULL,
    inbound_end          TIMESTAMP,
    outbound_start       TIMESTAMP NOT NULL,
    outbound_end         TIMESTAMP,
    status               VARCHAR(20) NOT NULL,
    inbound_avg          BIGINT NOT NULL,
    outbound_avg         BIGINT NOT NULL,
    outbound_rate        DOUBLE PRECISION NOT NULL,
    target_throughput    DOUBLE PRECISION NOT NULL,
    target_utilization   DOUBLE PRECISION NOT NULL,
    budget_limit         BIGINT NOT NULL
);
CREATE TABLE facility (
    facility_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(20) NOT NULL,
    x           DOUBLE PRECISION NOT NULL,
    y           DOUBLE PRECISION NOT NULL
);
CREATE TABLE zones (
    zone_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL,
    facility_id  BIGINT NOT NULL,
    zone_code    VARCHAR(10) NOT NULL,
    rack_count   INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE rack (
    rack_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL,
    field   VARCHAR(10) NOT NULL
);
CREATE TABLE stores (
    store_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id        BIGINT NOT NULL,
    name           VARCHAR(100) NOT NULL,
    category       VARCHAR(100) NOT NULL,
    outbound_count BIGINT
);
CREATE TABLE products (
    product_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id    BIGINT NOT NULL,
    rack_id     BIGINT NOT NULL,
    name        VARCHAR(100),
    price       INTEGER,
    count       INTEGER,
    count_init  INTEGER
);
CREATE TABLE orders (
    order_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id   BIGINT NOT NULL,
    order_at   TIMESTAMP,
    status     VARCHAR(20) NOT NULL,
    order_code VARCHAR(10) NOT NULL
);
CREATE TABLE simscenarios (
    scenario_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round             BIGINT NOT NULL,
    amr_count         INTEGER,
    utilization       DOUBLE PRECISION,
    outbound          BIGINT,
    throughput        DOUBLE PRECISION,
    total_cost        BIGINT
);
CREATE TABLE robots (
    robot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model    VARCHAR(100) NOT NULL DEFAULT 'iw.hub',
    battery  DOUBLE PRECISION NOT NULL,
    speed    DOUBLE PRECISION NOT NULL,
    capacity INTEGER NOT NULL,
    price    INTEGER NOT NULL,
    cost     INTEGER NOT NULL,
    x        DOUBLE PRECISION NOT NULL,
    y        DOUBLE PRECISION NOT NULL,
    status   VARCHAR(20) NOT NULL
);
CREATE TABLE tasks (
    task_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id       BIGINT NOT NULL,
    robot_id          BIGINT,
    from_facility_id  BIGINT NOT NULL,
    to_facility_id    BIGINT NOT NULL,
    type              VARCHAR(20) NOT NULL,
    status            VARCHAR(20),
    start_time        TIMESTAMP,
    end_time          TIMESTAMP
);
CREATE TABLE inbounds (
    inbound_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id   BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    task_id    BIGINT NOT NULL,
    count      INTEGER NOT NULL DEFAULT 1,
    status     VARCHAR(20) NOT NULL,
    inbound_at TIMESTAMP
);
CREATE TABLE outbounds (
    outbound_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id    BIGINT NOT NULL,
    order_id    BIGINT NOT NULL,
    product_id  BIGINT NOT NULL,
    task_id     BIGINT NOT NULL,
    count       INTEGER NOT NULL DEFAULT 1,
    status      VARCHAR(20) NOT NULL,
    outbound_at TIMESTAMP
);
CREATE TABLE workers (
    worker_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id   BIGINT NOT NULL,
    work_time VARCHAR(10) NOT NULL,
    pace      DOUBLE PRECISION NOT NULL,
    level     VARCHAR(10) DEFAULT 'MID'
);
